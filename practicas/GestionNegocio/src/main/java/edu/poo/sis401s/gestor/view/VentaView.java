    private void RegistrarventaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_RegistrarventaActionPerformed
          String producto = txtProducto.getText().trim();
String textoCantidad = txtCantidad.getText().trim();
String textoPrecio = txtPrecio.getText().trim();
String fecha = txtFecha.getText().trim();

if (producto.isEmpty() || textoCantidad.isEmpty()
        || textoPrecio.isEmpty() || fecha.isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "Completa todos los campos.");
    return;
}

try {
    int cantidad = Integer.parseInt(textoCantidad);
    double precio = Double.parseDouble(textoPrecio);

    Venta venta = new Venta(producto, cantidad, precio, fecha);

    if (controller.registrarVenta(venta)) {
        JOptionPane.showMessageDialog(this,
                "Venta registrada correctamente.");

        txtProducto.setText("");
        txtCantidad.setText("");
        txtPrecio.setText("");
        txtFecha.setText("");

        actualizarTabla();
    } else {
        JOptionPane.showMessageDialog(this,
                "No se pudo registrar la venta. Revisa los datos.");
    }

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this,
            "Cantidad debe ser un entero y precio un número válido.");
} // TODO add your handling code here:
    }//GEN-LAST:event_RegistrarventaActionPerformed

