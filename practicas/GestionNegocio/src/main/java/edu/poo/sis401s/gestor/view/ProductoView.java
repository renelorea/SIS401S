    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
String texto = txtBuscar.getText().trim();
if (texto.isEmpty()) {
    cargarTabla();
    return;
}
Producto p = productoController.buscarPorNombre(texto);
DefaultTableModel modelo = new DefaultTableModel(
    new Object[]{"ID", "Nombre", "Precio", "Stock"}, 0
);
if (p != null) {
    modelo.addRow(new Object[]{p.getId(), p.getNombre(), "$" + p.getPrecio(), p.getStock()});
} else {
    JOptionPane.showMessageDialog(this, "No se encontró el producto: " + texto);
}
tablaInv.setModel(modelo);        // TODO add your handling code here:
    }//GEN-LAST:event_btnBuscarActionPerformed

