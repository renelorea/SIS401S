    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
int fila = tablaInv.getSelectedRow();
if (fila == -1) {
    JOptionPane.showMessageDialog(this, "Selecciona un producto de la tabla para eliminarlo.");
    return;
}
int id = Integer.parseInt(tablaInv.getValueAt(fila, 0).toString());
if (productoController.eliminarProducto(id)) {
    JOptionPane.showMessageDialog(this, "Producto eliminado del almacén.");
    cargarTabla();
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnEliminarActionPerformed

